// Style Dictionary 5: builds build/css/tokens.css (CSS custom properties) and build/json/tokens.json (a flat list for the
// Storybook token pages) from tokens/*.json. Values live only in the token files; this file only formats them.
//
// tokens.css keeps the app's own names (--surface, --t-body, --s-8 ...) for every token taken from a custom property,
// so it can replace the :root blocks of web/app.css later without a rename. Tokens of values written out in rules get a
// name from their path (--duration-quick, --part-color-btn-hover-bg). The app does not load this file yet.
const NS = 'cc.pinned';
const MODES = ['dark', 'light'];
const MODED = ['color', 'shadow', 'gradient'];

const val = (t) => (t.$value !== undefined ? t.$value : t.value);
const typeOf = (t) => t.$type || t.type;
const meta = (t) => (t.$extensions && t.$extensions[NS]) || {};
const modeOf = (t) => (MODED.includes(t.path[0]) && MODES.includes(t.path[1]) ? t.path[1] : null);
const cssName = (t) => meta(t).var || '--' + t.path.join('-');

function rgba(c) {
  const [r, g, b] = c.components.map((x) => Math.round(x * 255));
  return { r, g, b, a: c.alpha === undefined ? 1 : c.alpha };
}
function cssColor(c) {
  const { r, g, b, a } = rgba(c);
  return a === 1 ? c.hex : `rgba(${r},${g},${b},${a})`;
}
const dim = (d) => `${d.value}${d.unit}`;
function cssValue(t) {
  const v = val(t);
  switch (typeOf(t)) {
    case 'color': return cssColor(v);
    case 'dimension': return dim(v);
    case 'number': return String(v);
    case 'fontWeight': return String(v);
    case 'duration': return dim(v);
    case 'cubicBezier': return `cubic-bezier(${v.join(',')})`;
    case 'fontFamily': return v.map((f) => (/^[a-z-]+$/.test(f) ? f : `"${f}"`)).join(',');
    case 'shadow': return (Array.isArray(v) ? v : [v]).map((s) => `${s.inset ? 'inset ' : ''}${dim(s.offsetX)} ${dim(s.offsetY)} ${dim(s.blur)} ${dim(s.spread)} ${cssColor(s.color)}`).join(',');
    default: return String(v); // raw CSS: gradients, filters, steps(1), 50%, shorthands
  }
}

const cssFormat = ({ dictionary }) => {
  const shared = [], byMode = { dark: [], light: [] };
  for (const t of dictionary.allTokens) {
    const line = `  ${cssName(t)}:${cssValue(t)};`;
    const m = modeOf(t);
    (m ? byMode[m] : shared).push(line);
  }
  return `/* Generated by Style Dictionary from design/tokens/*.json. Do not edit. */
:root{
${shared.join('\n')}
${byMode.dark.join('\n')}
}
:root[data-theme="light"]{
${byMode.light.join('\n')}
}
`;
};

const jsonFormat = ({ dictionary }) => JSON.stringify(dictionary.allTokens.map((t) => ({
  name: cssName(t), path: t.path.join('.'), type: typeOf(t) || 'css', mode: modeOf(t), css: cssValue(t),
  description: t.$description || '', source: meta(t).source || [], selector: meta(t).selector || null, property: meta(t).property || null,
  part: t.path[0] === 'part',
})), null, 2);

export default {
  source: ['tokens/*.json'],
  usesDtcg: true,
  log: { verbosity: 'default' },
  hooks: { formats: { 'pinned/css': cssFormat, 'pinned/json': jsonFormat } },
  platforms: {
    css: { buildPath: 'build/css/', transforms: ['name/kebab'], files: [{ destination: 'tokens.css', format: 'pinned/css' }] },
    json: { buildPath: 'build/json/', transforms: ['name/kebab'], files: [{ destination: 'tokens.json', format: 'pinned/json' }] },
  },
};
