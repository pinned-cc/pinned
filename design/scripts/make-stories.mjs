// Writes the part and screen stories from the fixtures that scripts/capture.mjs took from the real app.
// Storybook reads story names from the file, so each fixture gets its own export. Run after a capture.
import { readFileSync, readdirSync, writeFileSync, rmSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SB = join(HERE, '..', 'storybook');
const read = (d) => readdirSync(join(SB, 'fixtures', d)).filter((f) => f.endsWith('.json')).sort().map((f) => JSON.parse(readFileSync(join(SB, 'fixtures', d, f), 'utf8')));
const ident = (id) => id.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase()).replace(/^(\d)/, 'N$1');
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const q = JSON.stringify;

mkdirSync(join(SB, 'stories'), { recursive: true });
for (const f of readdirSync(join(SB, 'stories'))) if (/^(parts|screens)-.*\.stories\.js$/.test(f)) rmSync(join(SB, 'stories', f));

const ORDER = ['dark', 'light'];
const groups = {};
for (const fx of read('parts')) (groups[fx.group] ||= []).push(fx);
for (const [group, list] of Object.entries(groups)) {
  list.sort((a, b) => (a.device === b.device ? a.title.localeCompare(b.title) : a.device === 'desk' ? -1 : 1));
  let s = `// Generated by scripts/make-stories.mjs from storybook/fixtures/parts. Do not edit; capture again instead.
import { partFrame, themed } from '../src/frame.js';
${list.map((fx) => `import ${ident(fx.id)} from '../fixtures/parts/${fx.id}.json';`).join('\n')}

export default { title: ${q('Parts/' + group)}, parameters: { controls: { disable: true } } };
const story = (fx) => ({
  name: fx.title + (fx.device === 'phone' ? ', phone' : ''),
  parameters: { fixture: fx.id, device: fx.device, docs: { description: { story: fx.note } } },
  render: themed((theme) => {
    const wrap = document.createElement('div');
    wrap.innerHTML = \`<p class="ds-cap">\${fx.device === 'phone' ? 'Phone, 390 wide' : 'Desktop, 1440 wide'}. Markup from the app at 0.1.11; app.css as it ships.</p>\`;
    wrap.appendChild(partFrame(fx, theme));
    return wrap;
  }),
});
`;
  for (const fx of list) s += `export const ${ident(fx.id)}Story = story(${ident(fx.id)});\n`;
  writeFileSync(join(SB, 'stories', `parts-${slug(group)}.stories.js`), s);
}

const screens = read('screens');
for (const device of ['desk', 'phone']) {
  const list = screens.filter((x) => x.device === device);
  let s = `// Generated by scripts/make-stories.mjs from storybook/fixtures/screens. Do not edit; capture again instead.
import { screenFrame, themed } from '../src/frame.js';
${list.map((fx) => `import ${ident(fx.id)} from '../fixtures/screens/${fx.id}.json';`).join('\n')}

export default { title: ${q('Screens/' + (device === 'desk' ? 'Desktop' : 'Phone'))}, parameters: { controls: { disable: true } } };
const story = (fx) => ({ name: fx.title.replace(/, (desktop|phone)$/, ''), parameters: { fixture: fx.id, device: fx.device }, render: themed((theme) => screenFrame(fx, theme)) });
`;
  for (const fx of list) s += `export const ${ident(fx.id)}Story = story(${ident(fx.id)});\n`;
  writeFileSync(join(SB, 'stories', `screens-${device === 'desk' ? 'desktop' : 'phone'}.stories.js`), s);
}
console.log(`${Object.values(groups).flat().length} parts in ${Object.keys(groups).length} groups, ${screens.length} screens`);
